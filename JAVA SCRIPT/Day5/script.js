// TASK 1 – PRINT 1 TO 10
console.log("TASK 1 – PRINT 1 TO 10");
for (let i = 1; i <= 10; i++) {
    console.log(i);
}

// TASK 2 – PRINT 10 TO 1
console.log("TASK 2 – PRINT 10 TO 1");
for (let i = 10; i >= 1; i--) {
    console.log(i);
}

// TASK 3 – PRINT 1 TO 20
console.log("TASK 3 – PRINT 1 TO 20");
for (let i = 1; i <= 20; i++) {
    console.log(i);
}

// TASK 4 – PRINT EVEN NUMBERS FROM 1 TO 20
console.log("TASK 4 – EVEN NUMBERS");
for (let i = 1; i <= 20; i++) {
    if (i % 2 === 0) {
        console.log(i);
    }
}

// TASK 5 – PRINT ODD NUMBERS FROM 1 TO 20
console.log("TASK 5 – ODD NUMBERS");
for (let i = 1; i <= 20; i++) {
    if (i % 2 !== 0) {
        console.log(i);
    }
}
